// The only things Harbour's screen can ask the main process to do.
const { contextBridge, ipcRenderer } = require('electron');

const call = async (ch, ...args) => {
  const r = await ipcRenderer.invoke(ch, ...args);
  if (!r.ok) throw new Error(r.error);
  return r.value;
};
const on = channel => fn => ipcRenderer.on(channel, (_e, p) => fn(p));

contextBridge.exposeInMainWorld('api', {
  platform: process.platform,
  // settings and library
  getConfig: () => call('config:get'),
  setConfig: cfg => call('config:set', cfg),
  scan: (withReport, options) => call('library:scan', withReport, options),
  cachedLibrary: () => call('library:cached'),
  libraryUi: () => call('library:ui'),
  saveLibraryUi: patch => call('library:saveUi', patch),
  onLibraryInfo: on('library:info'),
  pickFolder: title => call('dialog:folder', title),
  addGameFolder: options => call('harbour:addGameFolder', options),
  removeGameFolder: options => call('harbour:removeGameFolder', options),
  // games
  launch: (id, options) => call('game:launch', id, options),
  quitGame: () => call('game:quit'),
  onGameStarted: on('game:started'),
  onGameEnded: on('game:ended'),
  setFavorite: options => call('game:setFavorite', options),
  mediaSet: options => call('media:set', options),
  mediaSizes: kind => call('media:sizes', kind),
  mediaUsage: kind => call('media:usage', kind),
  mediaClearAll: kind => call('media:clearAll', kind),
  mediaUnused: () => call('media:unused'),
  mediaDeleteUnused: () => call('media:deleteUnused'),
  setHidden: options => call('game:setHidden', options),
  setTitle: options => call('game:setTitle', options),
  openGameFolder: id => call('game:openFolder', id),
  chooseGameExecutable: id => call('game:chooseExecutable', id),
  pickPort: () => call('harbour:pickPort'),
  pickPortExe: folder => call('harbour:pickPortExe', folder),
  detectPort: options => call('harbour:detectPort', options),
  gameRemove: id => call('game:remove', id),
  gameDelete: id => call('game:delete', id),
  addPort: options => call('harbour:addPort', options),
  installPort: options => call('harbour:installPort', options),
  portCatalog: () => call('harbour:portCatalog'),
  pickGameFile: () => call('harbour:pickGameFile'),
  // emulators
  emuList: () => call('emu:list'),
  emuOpenFolder: id => call('emu:openFolder', id),
  emuOpen: id => call('emu:open', id),
  emuPickExe: id => call('emu:pickExe', id),
  emuRemove: id => call('emu:remove', id),
  addEmulator: options => call('harbour:addEmulator', options),
  scanEmulators: folder => call('harbour:scanEmulators', folder),
  installDirs: () => call('harbour:installDirs'),
  pickInstallDir: (kind, opts) => call('harbour:pickInstallDir', kind, opts),
  setInstallDir: options => call('harbour:setInstallDir', options),
  makeWelcomeFolders: () => call('harbour:makeWelcomeFolders'),
  setEmulator: options => call('harbour:setEmulator', options),
  setSystemEmulator: options => call('harbour:setSystemEmulator', options),
  setEmulatorSource: options => call('harbour:setEmulatorSource', options),
  checkEmulators: force => call('harbour:checkEmulators', force),
  openEmulatorPage: id => call('harbour:openEmulatorPage', id),
  emuUpdate: id => call('harbour:emuUpdate', id),
  emulatorCatalog: () => call('harbour:emulatorCatalog'),
  installEmulator: id => call('harbour:installEmulator', id),
  selfStatus: force => call('harbour:selfStatus', force),
  selfUpdate: () => call('harbour:selfUpdate'),
  sendFeedback: f => call('feedback:send', f),
  pauseDownload: (key, on) => call('downloads:pause', { key, on }),
  // cloud saves (OpenSave)
  saves: {
    status: () => call('saves:status'), states: () => call('saves:states'), enable: () => call('saves:enable'), disable: () => call('saves:disable'),
    newCode: () => call('saves:newCode'), joinCode: code => call('saves:joinCode', code), link: peer => call('saves:link', peer),
    approve: id => call('saves:approve', id), reject: id => call('saves:reject', id), unlink: id => call('saves:unlink', id),
    leaveCode: () => call('saves:leaveCode'), suggest: title => call('saves:suggest', title), pickFolder: title => call('saves:pickFolder', title),
    track: o => call('saves:track', o), untrack: id => call('saves:untrack', id), place: o => call('saves:place', o),
    decline: id => call('saves:decline', id), resolve: o => call('saves:resolve', o), syncNow: () => call('saves:syncNow'),
    openFolder: p => call('saves:openFolder', p), useFolder: () => call('saves:useFolder'), dropbox: () => call('saves:dropbox'),
    disconnectCloud: () => call('saves:disconnectCloud'), onProgress: on('saves:progress'),
  },
  // recomp updates
  recompGet: id => call('recomp:get', id),
  recompSet: opts => call('recomp:set', opts),
  recompCheck: (id, force) => call('recomp:check', id, force),
  recompCheckAll: force => call('recomp:checkAll', force),
  recompUpdate: id => call('recomp:update', id),
  runPortLauncher: id => call('recomp:runLauncher', id),
  whatsNew: () => call('harbour:whatsNew'), notes: () => call('harbour:notes'),
  onRecheck: on('recomp:recheck'),
  recompOpenPage: id => call('recomp:openPage', id),
  onRecompProgress: on('recomp:progress'),
  // artwork and videos
  artStart: options => call('art:start', options),
  onArtProgress: on('art:progress'),
  videoStart: options => call('video:start', options),
  videoStatus: () => call('video:status'),
  onVideoProgress: on('video:progress'),
  // window
  isFullscreen: () => call('app:fullscreen'),
  setFullscreen: on => call('app:setFullscreen', on),
  onToast: on('toast'),
  quitApp: () => ipcRenderer.send('app:quit'),
});
